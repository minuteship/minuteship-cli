import { chmod, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { wranglerRun } from '../adapters/wrangler.js';
import { parseEnvFile } from '../env-file.js';
import { run } from '../exec.js';
import { quoteEnvValue } from '../options/env.js';
import { OPTIONS } from '../options/registry.js';
import { pathExists } from '../files.js';
import { readState, recordStep } from '../state.js';
import { seedPaymentPrices } from './seed.js';
import type { Logger } from '../log.js';
import type { PackageManager } from '../types.js';

export interface DeployCommandInput {
  targetDir: string;
  packageManager: PackageManager;
  dryRun: boolean;
  logger: Logger;
  env?: NodeJS.ProcessEnv;
  skipMigrate?: boolean;
  skipBuild?: boolean;
}

export interface DeployResult {
  deployed: boolean;
  url?: string;
  secretNames: string[];
}

const WORKER_SECRET_FILE = '.minuteship/worker-secrets.env';

function workerSecretKeys(): string[] {
  return OPTIONS.filter(
    (spec) => spec.envVar && spec.targets?.includes('worker.secret')
  ).map((spec) => spec.envVar as string);
}

/**
 * Build the Worker-secret file from `.env.production`, limited to keys the
 * runtime actually reads. `VITE_*` values are build-time only and stay out.
 */
export function buildWorkerSecrets(
  production: Record<string, string>
): { content: string; names: string[] } {
  const names = workerSecretKeys().filter(
    (name) => production[name] !== undefined && production[name] !== ''
  );

  const content = [
    '# Generated by create-minuteship. Removed after upload.',
    ...names.map((name) => `${name}=${quoteEnvValue(production[name] as string)}`),
    '',
  ].join('\n');

  return { content, names };
}

export async function runDeploy(
  input: DeployCommandInput
): Promise<DeployResult> {
  const { targetDir, packageManager, logger } = input;
  const wranglerContext = { targetDir, packageManager };

  if (!(await pathExists(path.join(targetDir, 'wrangler.jsonc')))) {
    throw new Error(
      `${targetDir} has no wrangler.jsonc. Run the command from the project directory.`
    );
  }

  const state = await readState(targetDir);
  const production = await parseEnvFile(
    path.join(targetDir, '.env.production')
  );
  const secrets = buildWorkerSecrets(production);
  const url = production.VITE_BASE_URL;

  if (input.dryRun) {
    logger.plain(
      [
        'Deploy plan:',
        `  1. Apply remote migrations (${packageManager} db:migrate:remote)`,
        `  2. Seed payment price ids for ${production.VITE_PAYMENT_PROVIDER || '(no provider)'}`,
        `  3. Upload ${secrets.names.length} Worker secrets: ${secrets.names.join(', ') || '(none)'}`,
        `  4. Build (${packageManager} build)`,
        '  5. Deploy (wrangler deploy)',
        url ? `  6. Verify ${url}` : '  6. No VITE_BASE_URL; skipping verification',
      ].join('\n')
    );
    return { deployed: false, secretNames: secrets.names };
  }

  if (!input.skipMigrate) {
    logger.info('Applying remote database migrations…');
    await run(packageManager, ['db:migrate:remote'], { cwd: targetDir });
    await recordStep(targetDir, 'migrate-remote', 'done');
  }

  if (state?.cloudflare?.databaseName) {
    try {
      await seedPaymentPrices({
        targetDir,
        packageManager,
        databaseName: state.cloudflare.databaseName,
        provider: production.VITE_PAYMENT_PROVIDER ?? '',
        env: production,
        logger,
      });
      await recordStep(targetDir, 'seed-prices', 'done');
    } catch (error) {
      // A deploy must not fail because price metadata could not be written:
      // build-time ids still work for the provider chosen at scaffolding time.
      logger.warn(
        `Skipped payment price seeding: ${
          error instanceof Error ? error.message : String(error)
        }`
      );
    }
  }

  const secretFile = path.join(targetDir, WORKER_SECRET_FILE);
  if (secrets.names.length > 0) {
    logger.info(`Uploading ${secrets.names.length} Worker secrets…`);
    await writeFile(secretFile, secrets.content, { encoding: 'utf8', mode: 0o600 });
    try {
      await chmod(secretFile, 0o600);
      await wranglerRun(wranglerContext, [
        'secret',
        'bulk',
        WORKER_SECRET_FILE,
      ]);
      await recordStep(targetDir, 'worker-secrets', 'done');
    } finally {
      await rm(secretFile, { force: true });
    }
  } else {
    logger.verbose('No runtime secrets to upload.');
  }

  if (!input.skipBuild) {
    logger.info('Building the site…');
    await run(packageManager, ['build'], { cwd: targetDir });
  }

  logger.info('Deploying to Cloudflare Workers…');
  const deploy = await wranglerRun(wranglerContext, ['deploy'], {
    redact: Object.values(production),
  });
  logger.verbose(deploy.stdout.trim());

  if (state?.cloudflare?.workerName) {
    await recordStep(targetDir, 'deploy', 'done', state.cloudflare.workerName);
  }

  if (url) {
    try {
      const response = await fetch(url, {
        signal: AbortSignal.timeout(15_000),
        headers: { 'cache-control': 'no-cache' },
      });
      logger.success(`Deployed. ${url} responded with ${response.status}.`);
    } catch (error) {
      logger.warn(
        `Deployed, but ${url} did not respond yet: ${
          error instanceof Error ? error.message : String(error)
        }`
      );
    }
  }

  return { deployed: true, url, secretNames: secrets.names };
}
